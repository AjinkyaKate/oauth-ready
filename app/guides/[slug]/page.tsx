import Link from "next/link";
import { notFound } from "next/navigation";
import { getGuide, allGuides } from "@/lib/guides";
import { Difficulty, EvidenceTag, Managed, Owner } from "@/components/badges";
import ShareButtons from "@/components/ShareButtons";

export const dynamic = "force-dynamic";

const STAGE_LABEL: Record<string, string> = {
  register: "1. Register",
  self_test: "2. Works for you",
  limited: "3. Limited users",
  public: "4. Anyone can connect",
};

export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }) {
  const g = await getGuide((await params).slug);
  return { title: g ? `${g.name} OAuth setup guide` : "Guide not found", description: g?.verdict.headline };
}

export default async function GuidePage({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const g = await getGuide(slug);
  if (!g) notFound();
  const total = await allGuides();
  const stepCount = g.stages.reduce((n, s) => n + s.steps.length, 0);
  const agentSteps = g.stages.reduce((n, s) => n + s.steps.filter((x) => x.owner === "agent").length, 0);

  return (
    <main className="mx-auto max-w-4xl px-4 pb-24 pt-6 sm:px-6">
      <nav className="mb-6 text-sm text-slate-500 print:hidden">
        <Link href="/" className="hover:text-slate-900">
          ← All guides ({total.length})
        </Link>
      </nav>

      <header className="flex flex-wrap items-start justify-between gap-4">
        <div>
          <h1 className="text-3xl font-bold tracking-tight text-slate-900">{g.name}: OAuth app setup</h1>
          <div className="mt-2 flex flex-wrap items-center gap-2 text-sm text-slate-600">
            {g.provider && <span>{g.provider}</span>}
            <Managed managed={g.composio.managed_oauth} />
            <span className="rounded-full bg-slate-100 px-2 py-0.5 text-xs">
              {g.generated_by === "agent" ? "Generated by agent" : "Curated and checked"} · updated {g.updated_at}
            </span>
          </div>
        </div>
        <ShareButtons slug={g.slug} />
      </header>

      {/* Readiness card: the decision a developer needs before reading any steps */}
      <section className="mt-6 rounded-2xl border border-slate-200 bg-white p-5 shadow-sm sm:p-6">
        <div className="flex flex-wrap items-center gap-3">
          <Difficulty level={g.verdict.difficulty} large />
          <span className="text-sm text-slate-600">
            Approval to go public: <b className="text-slate-900">{g.verdict.approval}</b>
          </span>
          <EvidenceTag ev={g.verdict.evidence} guide={g} />
        </div>
        <p className="mt-3 text-lg leading-snug text-slate-900">{g.verdict.headline}</p>
        <dl className="mt-5 grid grid-cols-1 gap-3 sm:grid-cols-3">
          {[
            ["Your hands-on work", g.verdict.hands_on_time],
            ["You can connect your own account", g.verdict.first_connection],
            ["Any user can connect", g.verdict.public_launch],
          ].map(([k, v]) => (
            <div key={k} className="rounded-xl bg-slate-50 p-3">
              <dt className="text-xs font-medium uppercase tracking-wide text-slate-500">{k}</dt>
              <dd className="mt-1 text-base font-semibold text-slate-900">{v}</dd>
            </div>
          ))}
        </dl>
        {g.verdict.time_note && <p className="mt-3 text-sm text-slate-700">{g.verdict.time_note}</p>}
        <p className="mt-4 text-sm text-slate-600">
          {stepCount} steps · an agent can do {agentSteps} of them · {g.blockers.length} possible blockers ·{" "}
          {g.uncertain.length} open questions
        </p>
      </section>

      <section
        className={`mt-4 rounded-xl p-4 text-sm ${
          g.composio.managed_oauth ? "bg-indigo-50 text-indigo-950" : "bg-slate-100 text-slate-800"
        }`}
      >
        <b>On Composio: </b>
        {g.composio.managed_oauth
          ? "You can start today on Composio's managed OAuth app (users will see Composio on the consent screen). Register your own app in parallel, and switch the auth config once it is approved. Existing connections stay on the old config until users reconnect."
          : "Composio has no managed app for this toolkit, so nothing connects until your own OAuth app exists. Start the steps below first."}
        {g.composio.note && <span className="mt-1 block">{g.composio.note}</span>}
        {g.redirect_uri && (
          <span className="mt-2 block">
            Redirect URI to register: <code className="rounded bg-white/70 px-1 py-0.5 text-xs">{g.redirect_uri}</code>
          </span>
        )}
      </section>

      <h2 className="mt-10 text-xl font-bold text-slate-900">Your path</h2>
      <p className="mt-1 text-sm text-slate-600">
        Each stage unlocks more users. Most developers only need the first two to build and demo.
      </p>
      <ol className="mt-4 space-y-4">
        {g.stages.map((s) => (
          <li key={s.id + s.title} className="rounded-xl border border-slate-200 bg-white p-4 sm:p-5">
            <div className="flex flex-wrap items-baseline justify-between gap-2">
              <h3 className="font-semibold text-slate-900">
                <span className="text-slate-400">{STAGE_LABEL[s.id] ?? s.id}</span> · {s.title}
              </h3>
              <span className="text-xs text-slate-500">
                Approval: {s.approval} · Wait: {s.wait}
              </span>
            </div>
            <p className="mt-1 text-sm text-slate-700">
              <b>Who can connect:</b> {s.who_can_connect}
              {s.limits && (
                <>
                  {" "}
                  · <b>Limits:</b> {s.limits}
                </>
              )}
            </p>
            <ul className="mt-3 space-y-2">
              {s.steps.map((st, i) => (
                <li key={i} className="flex gap-2 text-sm">
                  <Owner owner={st.owner} />
                  <div className="min-w-0">
                    <span className="text-slate-900">{st.text}</span>{" "}
                    {st.url && (
                      <a href={st.url} target="_blank" className="break-all text-sky-700 hover:underline">
                        open ↗
                      </a>
                    )}{" "}
                    <EvidenceTag ev={st.evidence} guide={g} />
                  </div>
                </li>
              ))}
            </ul>
          </li>
        ))}
      </ol>

      {g.blockers.length > 0 && (
        <>
          <h2 className="mt-10 text-xl font-bold text-slate-900">What can block you</h2>
          <div className="mt-4 grid gap-3 sm:grid-cols-2">
            {g.blockers.map((b, i) => (
              <div key={i} className="rounded-xl border border-rose-200 bg-rose-50/50 p-4 text-sm">
                <h3 className="font-semibold text-slate-900">{b.title}</h3>
                <p className="mt-1 text-slate-700">
                  <b>When:</b> {b.when}
                </p>
                <p className="mt-1 text-slate-700">
                  <b>Impact:</b> {b.impact}
                </p>
                {b.workaround && (
                  <p className="mt-1 text-slate-700">
                    <b>Way around it:</b> {b.workaround}
                  </p>
                )}
                <div className="mt-2">
                  <EvidenceTag ev={b.evidence} guide={g} />
                </div>
              </div>
            ))}
          </div>
        </>
      )}

      <div className="mt-10 grid gap-6 sm:grid-cols-2">
        <div>
          <h2 className="text-xl font-bold text-slate-900">What an agent can do</h2>
          <ul className="mt-3 list-disc space-y-1 pl-5 text-sm text-slate-700">
            {g.agent_can.map((x, i) => (
              <li key={i}>{x}</li>
            ))}
          </ul>
        </div>
        <div>
          <h2 className="text-xl font-bold text-slate-900">Where you take over</h2>
          <ul className="mt-3 list-disc space-y-1 pl-5 text-sm text-slate-700">
            {g.you_must.map((x, i) => (
              <li key={i}>{x}</li>
            ))}
          </ul>
        </div>
      </div>

      {g.requirements.length > 0 && (
        <>
          <h2 className="mt-10 text-xl font-bold text-slate-900">Requirements and nuances</h2>
          <ul className="mt-3 space-y-2 text-sm">
            {g.requirements.map((r, i) => (
              <li key={i} className="text-slate-800">
                {r.text}
                {r.applies_when && <span className="text-slate-500"> (when: {r.applies_when})</span>}{" "}
                <EvidenceTag ev={r.evidence} guide={g} />
              </li>
            ))}
          </ul>
        </>
      )}

      {g.scopes.length > 0 && (
        <>
          <h2 className="mt-10 text-xl font-bold text-slate-900">Scopes to know</h2>
          <div className="mt-3 overflow-x-auto">
            <table className="w-full text-left text-sm">
              <thead className="text-xs uppercase text-slate-500">
                <tr>
                  <th className="py-2 pr-4">Scope</th>
                  <th className="py-2 pr-4">Tier</th>
                  <th className="py-2">Note</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {g.scopes.map((s, i) => (
                  <tr key={i}>
                    <td className="py-2 pr-4 font-mono text-xs">{s.scope}</td>
                    <td className="py-2 pr-4">{s.tier}</td>
                    <td className="py-2 text-slate-700">{s.note}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </>
      )}

      {g.uncertain.length > 0 && (
        <>
          <h2 className="mt-10 text-xl font-bold text-slate-900">What we could not confirm</h2>
          <ul className="mt-3 list-disc space-y-1 pl-5 text-sm text-amber-900">
            {g.uncertain.map((x, i) => (
              <li key={i}>{x}</li>
            ))}
          </ul>
        </>
      )}

      {g.verification_log.length > 0 && (
        <>
          <h2 className="mt-10 text-xl font-bold text-slate-900">How this guide was checked</h2>
          <ul className="mt-3 space-y-2 text-sm">
            {g.verification_log.map((v, i) => (
              <li key={i} className="rounded-lg bg-slate-50 p-3">
                <span className="text-slate-500">
                  {v.date} · {v.method}
                </span>
                <div className="text-slate-900">{v.what}</div>
                <div className="text-slate-700">Result: {v.result}</div>
              </li>
            ))}
          </ul>
        </>
      )}

      <h2 className="mt-10 text-xl font-bold text-slate-900">Sources</h2>
      <ol className="mt-3 space-y-1 text-sm">
        {g.sources.map((s) => (
          <li key={s.id} id={`src-${s.id}`} className="scroll-mt-20">
            <span className="text-slate-500">[{s.id}]</span>{" "}
            <a href={s.url} target="_blank" className="text-sky-700 hover:underline">
              {s.title}
            </a>
            {s.accessed && <span className="text-slate-400"> · accessed {s.accessed}</span>}
          </li>
        ))}
      </ol>
    </main>
  );
}
