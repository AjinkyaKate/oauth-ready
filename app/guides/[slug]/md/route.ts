import { getGuide } from "@/lib/guides";
import type { Evidence, Guide } from "@/lib/schema";

// Plain Markdown version of a guide, so it can be pasted into a ticket, PR or doc.
export async function GET(_req: Request, { params }: { params: Promise<{ slug: string }> }) {
  const g = await getGuide((await params).slug);
  if (!g) return new Response("Not found", { status: 404 });
  return new Response(toMarkdown(g), { headers: { "Content-Type": "text/markdown; charset=utf-8" } });
}

const ev = (e: Evidence) => ` _(${e.type}${e.sources.length ? " " + e.sources.map((s) => `[${s}]`).join("") : ""})_`;

function toMarkdown(g: Guide) {
  const L: string[] = [];
  L.push(`# ${g.name}: OAuth app setup guide`, "");
  L.push(`**Difficulty:** ${g.verdict.difficulty} · **Approval to go public:** ${g.verdict.approval}`, "");
  L.push(`> ${g.verdict.headline}`, "");
  L.push(`- Your hands-on work: ${g.verdict.hands_on_time}`);
  L.push(`- You can connect your own account: ${g.verdict.first_connection}`);
  L.push(`- Any user can connect: ${g.verdict.public_launch}`);
  if (g.verdict.time_note) L.push(`- ${g.verdict.time_note}`);
  L.push(`- Composio-managed app: ${g.composio.managed_oauth ? "yes, you can start on it today" : "no, bring your own OAuth app"}`);
  if (g.redirect_uri) L.push(`- Redirect URI: \`${g.redirect_uri}\``);
  L.push("", "## Your path", "");
  for (const s of g.stages) {
    L.push(`### ${s.title}`, `Who can connect: ${s.who_can_connect}. Approval: ${s.approval}. Wait: ${s.wait}.${s.limits ? ` Limits: ${s.limits}.` : ""}`, "");
    for (const st of s.steps) L.push(`- [ ] **${st.owner}**: ${st.text}${st.url ? ` (${st.url})` : ""}${ev(st.evidence)}`);
    L.push("");
  }
  if (g.blockers.length) {
    L.push("## What can block you", "");
    for (const b of g.blockers)
      L.push(`- **${b.title}** (when: ${b.when}). ${b.impact}${b.workaround ? ` Way around it: ${b.workaround}` : ""}${ev(b.evidence)}`);
    L.push("");
  }
  L.push("## What an agent can do", "", ...g.agent_can.map((x) => `- ${x}`), "");
  L.push("## Where you take over", "", ...g.you_must.map((x) => `- ${x}`), "");
  if (g.uncertain.length) L.push("## Not confirmed", "", ...g.uncertain.map((x) => `- ${x}`), "");
  L.push("## Sources", "", ...g.sources.map((s) => `- [${s.id}] ${s.title}: ${s.url}`), "");
  L.push(`_${g.generated_by === "agent" ? "Generated by agent" : "Curated"}, updated ${g.updated_at}._`);
  return L.join("\n");
}
