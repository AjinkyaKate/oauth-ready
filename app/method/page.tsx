import Link from "next/link";
import { allGuides } from "@/lib/guides";

export const dynamic = "force-dynamic";
export const metadata = { title: "How these guides are made" };

export default async function Method() {
  const guides = await allGuides();
  const counts = { tested: 0, sourced: 0, uncertain: 0 };
  for (const g of guides)
    for (const m of JSON.stringify(g).matchAll(/"type":"(tested|sourced|uncertain)"/g)) counts[m[1] as keyof typeof counts]++;
  const checks = guides.flatMap((g) => g.verification_log.map((v) => ({ ...v, app: g.name, slug: g.slug })));

  return (
    <main className="mx-auto max-w-3xl px-4 pb-24 pt-10 sm:px-6">
      <Link href="/" className="text-sm text-slate-500 hover:text-slate-900">
        ← All guides
      </Link>
      <h1 className="mt-6 text-3xl font-bold tracking-tight text-slate-900">How these guides are made</h1>

      <div className="mt-6 space-y-4 text-slate-700">
        <p>
          <b>Research.</b> An agent reads the provider&apos;s current developer docs, app review or verification policies and pricing
          pages, and writes the guide in a fixed format. Official provider docs come first. Anything from blogs, forums or vendor
          pages is marked Uncertain.
        </p>
        <p>
          <b>Setup attempts.</b> Where it is practical, we register a real test OAuth app with the Composio redirect URI and record what
          the provider actually shows. Those claims are marked Tested. Approvals that take weeks or need a live product (Google CASA,
          Slack Marketplace, Shopify App Store) are not attempted.
        </p>
        <p>
          <b>Spot checks.</b> A second pass re-reads the source for high-stakes claims (user caps, rate limits, scope tiers, prices,
          cutoff dates) and corrects the guide when the source does not say what the guide claims.
        </p>
        <p>
          <b>Live generation.</b> For apps outside the library, the same agent runs on demand with web search and page fetch, streams
          what it is checking, and returns a guide in the same format with the same evidence tags. Those guides are labeled
          &quot;Generated by agent&quot; and are not human-reviewed.
        </p>
      </div>

      <h2 className="mt-10 text-xl font-bold text-slate-900">Evidence across {guides.length} guides</h2>
      <dl className="mt-4 grid grid-cols-3 gap-3">
        {(
          [
            ["Tested", counts.tested, "text-emerald-700"],
            ["Sourced", counts.sourced, "text-sky-700"],
            ["Uncertain", counts.uncertain, "text-amber-700"],
          ] as const
        ).map(([k, v, c]) => (
          <div key={k} className="rounded-xl border border-slate-200 bg-white p-4">
            <dt className="text-xs uppercase tracking-wide text-slate-500">{k}</dt>
            <dd className={`mt-1 text-2xl font-bold ${c}`}>{v}</dd>
          </div>
        ))}
      </dl>

      <h2 className="mt-10 text-xl font-bold text-slate-900">Check log</h2>
      <ul className="mt-4 space-y-2 text-sm">
        {checks.map((v, i) => (
          <li key={i} className="rounded-lg bg-white p-3 ring-1 ring-slate-200">
            <span className="text-slate-500">
              {v.date} · {v.method} ·{" "}
              <Link className="underline" href={`/guides/${v.slug}`}>
                {v.app}
              </Link>
            </span>
            <div className="text-slate-900">{v.what}</div>
            <div className="text-slate-700">{v.result}</div>
          </li>
        ))}
      </ul>
    </main>
  );
}
